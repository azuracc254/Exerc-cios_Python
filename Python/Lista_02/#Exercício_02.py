print("Convertendo celcius em fahrenheit\n")
#Recebe um valor em graus célcius
celcius = float(input("Informe a temperatura em celcius: "))
#Fórmula que converte céclcius em fahrenheit c=(f * 9/5) + 32 ou f=(c * 1.8) + 32
fahrenheit = (celcius * 1.8) + 32
print("A temperatura em fahrenheit é: ",fahrenheit)