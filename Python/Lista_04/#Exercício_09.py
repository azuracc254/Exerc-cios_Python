print("Escreva um número maior que zero: ")
numero = float(input("Digite o número aqui: "))
#Cáculo da raiz em termos matemáticos é o inverso da potencia
raiz = numero **(1/2)
print(f"A raiz do número é {raiz:.2f}")
#Elevando aquarta potência
potencia = numero ** 4
print(f"A quarta potência do número é: {potencia} ")
#Obetendo o quociente do número divido por dois
quociente = numero / 2
#Multiplicando o mesmo pelo seu quociente
vezes_quociente = numero * quociente
print(f"O número recebido vezes o quociente é: {vezes_quociente}")
