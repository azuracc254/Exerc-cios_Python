#Lê as medidas do triângulo e declaras as variáveis
print("===Geometria Plana===")
print("Calculo de área de triângulo")
base_triangulo = float(input("Digite a base do triângulo: "))
altura_triangulo = float(input("Digite a altura do triângulo: "))
#Fórmula que calcula a área
area_triangulo = base_triangulo * altura_triangulo / 2
print(f"A área do triangulo confrome as medidas listadas é: {area_triangulo}")